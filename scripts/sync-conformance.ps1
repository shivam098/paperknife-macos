<#
.SYNOPSIS
Copies the conformance corpus from a checkout of PaperKnife for Windows into conformance/.

.DESCRIPTION
The corpus (documents, steps and the observations of the Windows engine) is generated by
PaperKnife for Windows. This copies it here and records the commit it came from in
conformance/SOURCE, so the port and the corpus it passes can be traced to the same Windows code.

.EXAMPLE
pwsh scripts/sync-conformance.ps1 -Windows ../paperknife-windows
#>
param(
    [Parameter(Mandatory)]
    [string]$Windows
)

$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$windowsRoot = (Resolve-Path $Windows).Path
$source = Join-Path $windowsRoot 'conformance'
if (-not (Test-Path (Join-Path $source 'cases'))) {
    throw "There is no corpus in $source."
}

$commit = (git -C $windowsRoot rev-parse HEAD).Trim()
$changes = git -C $windowsRoot status --porcelain -- conformance
$destination = Join-Path $root 'conformance'
if (Test-Path $destination) {
    Remove-Item $destination -Recurse -Force
}

Copy-Item $source $destination -Recurse
$note = if ($changes) { ' (plus changes not yet committed there)' } else { '' }
Set-Content -Path (Join-Path $destination 'SOURCE') -Value "shivam098/paperknife-windows@$commit$note" -Encoding ascii
$count = (Get-ChildItem (Join-Path $destination 'cases') -Filter *.json).Count
Write-Output "Copied $count cases from paperknife-windows@$commit$note."
